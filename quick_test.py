"""
Simple test to verify GenAI fix
"""
import requests
import json

response = requests.post(
    "http://localhost:5000/predict/explain-policy",
    json={"year": 2030},
    timeout=30
)

print("Status Code:", response.status_code)
print("\nFull Response:")
print(json.dumps(response.json(), indent=2))

data = response.json()
print("\n" + "="*70)
print("KEY CHECKS:")
print("="*70)
print(f"GenAI Enabled: {data.get('genai_enabled')}")
print(f"Number of Policy Insights: {len(data.get('policy_insights', []))}")

if data.get('policy_insights'):
    for i, insight in enumerate(data['policy_insights'], 1):
        source = insight.get('source', 'unknown')
        print(f"\nInsight {i} Source: {source}")
        if source == 'genai':
            print("  ✅ Generated by LLM!")
        else:
            print(f"  ⚠️  Using {source} mode")
