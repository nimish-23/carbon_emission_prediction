"""
Quick test script to generate policy recommendations
This tests the full pipeline: prediction → SHAP → policy insights
"""
import json
from core.prediction import predict_drivers_for_year
from core.shap_explainer import explain_prediction_with_shap
from policy.responsibility import build_responsibility_profile
from policy.policy_engine import generate_policy_insights

def test_policy_generation(year=2030, use_genai=True):
    """
    Generate policy recommendations for a given year
    
    Args:
        year: Prediction year (e.g., 2030, 2040, 2050)
        use_genai: Whether to use GenAI (requires Ollama) or rule-based
    """
    print("=" * 70)
    print(f"🌍 Generating Policy Recommendations for Year {year}")
    print("=" * 70)
    
    # Step 1: Predict energy drivers
    print(f"\n📊 Step 1: Predicting energy drivers for {year}...")
    drivers_pred = predict_drivers_for_year(year)
    print("✓ Drivers predicted:")
    for driver, value in drivers_pred.items():
        print(f"  - {driver}: {value:.3f}")
    
    # Step 2: Get CO₂ prediction + SHAP explanation
    print(f"\n🧠 Step 2: Generating SHAP explanation...")
    explanation = explain_prediction_with_shap(drivers_pred)
    print(f"✓ CO₂ Prediction: {explanation['prediction']:.3f} tonnes per capita")
    print(f"✓ Baseline: {explanation['baseline']:.3f} tonnes per capita")
    print(f"✓ Change: {explanation['prediction'] - explanation['baseline']:+.3f} tonnes")
    
    print("\n  Top Contributors:")
    for factor, pct in explanation['percentages'].items():
        contrib = explanation['contributions'][factor]
        print(f"  - {factor}: {contrib:+.4f} tonnes ({pct:.1f}%)")
    
    # Step 3: Build responsibility profile
    print(f"\n🎯 Step 3: Building responsibility profile...")
    responsibility_profile = build_responsibility_profile(explanation)
    print(f"✓ {len(responsibility_profile)} factors in profile")
    
    # Step 4: Generate policy insights
    print(f"\n🏛️  Step 4: Generating policy insights...")
    if use_genai:
        print("   Using GenAI (Ollama) - This may take 10-30 seconds...")
    else:
        print("   Using rule-based approach...")
    
    policy_insights = generate_policy_insights(
        responsibility_profile,
        use_genai=use_genai,
        explanation=explanation,
        year=year
    )
    
    # Display results
    print("\n" + "=" * 70)
    print("📋 POLICY RECOMMENDATIONS")
    print("=" * 70)
    
    for i, insight in enumerate(policy_insights, 1):
        print(f"\n{i}. {insight.get('theme') or insight.get('policy_area', 'Policy Area')}")
        print(f"   {'-' * 65}")
        
        rationale = insight.get('why_it_matters') or insight.get('rationale', 'N/A')
        print(f"   Why: {rationale}")
        
        actions = insight.get('policy_focus') or insight.get('actions', [])
        if actions:
            print(f"   Actions:")
            for action in actions[:3]:  # Show max 3 actions
                print(f"     • {action}")
        
        if 'source' in insight and insight['source'] == 'genai':
            print(f"   [Generated by GenAI]")
    
    print("\n" + "=" * 70)
    
    # Check if GenAI was actually used
    genai_used = any(ins.get('source') == 'genai' for ins in policy_insights)
    if use_genai and genai_used:
        print("✅ GenAI Successfully Generated Recommendations!")
    elif use_genai and not genai_used:
        print("⚠️  GenAI was requested but rule-based fallback was used")
        print("   (Check if Ollama is running: ollama serve)")
    else:
        print("✅ Rule-based Recommendations Generated")
    
    print("=" * 70)
    
    # Save to JSON file
    output = {
        'year': year,
        'prediction': round(explanation['prediction'], 3),
        'baseline': round(explanation['baseline'], 3),
        'drivers': {k: round(v, 3) for k, v in drivers_pred.items()},
        'shap_explanation': {
            'contributions': {k: round(v, 4) for k, v in explanation['contributions'].items()},
            'percentages': {k: round(v, 1) for k, v in explanation['percentages'].items()}
        },
        'policy_recommendations': policy_insights,
        'genai_enabled': genai_used
    }
    
    filename = f"policy_recommendation_{year}.json"
    with open(filename, 'w') as f:
        json.dump(output, f, indent=2)
    
    print(f"\n💾 Full output saved to: {filename}\n")
    
    return policy_insights


