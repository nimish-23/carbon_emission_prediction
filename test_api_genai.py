"""
Test actual API endpoint to verify GenAI is working
"""
import requests
import json

def test_api_endpoint():
    """Test the /predict/explain-policy endpoint"""
    print("=" * 70)
    print("Testing /predict/explain-policy Endpoint")
    print("=" * 70)
    
    url = "http://localhost:5000/predict/explain-policy"
    payload = {"year": 2030}
    
    print(f"\nRequest: POST {url}")
    print(f"Payload: {json.dumps(payload, indent=2)}")
    
    try:
        print("\nSending request (this may take 10-15 seconds for LLM generation)...")
        response = requests.post(url, json=payload, timeout=30)
        
        print(f"\nStatus Code: {response.status_code}")
        
        if response.status_code == 200:
            data = response.json()
            
            print("\n✓ Response received successfully!")
            print("\n" + "=" * 70)
            print("Response Summary:")
            print("=" * 70)
            
            print(f"\nYear: {data.get('year')}")
            print(f"Predicted CO₂ per capita: {data.get('predicted_co2_per_capita')}")
            print(f"Baseline: {data.get('baseline')}")
            print(f"GenAI Enabled: {data.get('genai_enabled')}")
            
            print(f"\n\nResponsibility Profile ({len(data.get('responsibility_profile', []))} factors):")
            for item in data.get('responsibility_profile', [])[:3]:
                print(f"  • {item['factor']}: {item['impact_percent']}% impact")
            
            print(f"\n\nPolicy Insights ({len(data.get('policy_insights', []))} recommendations):")
            for i, insight in enumerate(data.get('policy_insights', []), 1):
                print(f"\n  {i}. {insight.get('theme', insight.get('policy_area', 'N/A'))}")
                print(f"     Source: {insight.get('source', 'unknown')}")
                
                # Check for different response formats
                if 'why_it_matters' in insight:
                    print(f"     Why: {insight['why_it_matters'][:100]}...")
                if 'rationale' in insight:
                    print(f"     Rationale: {insight['rationale'][:100]}...")
                if 'policy_focus' in insight and insight['policy_focus']:
                    print(f"     Actions ({len(insight['policy_focus'])}):")
                    for action in insight['policy_focus'][:2]:
                        print(f"       - {action[:80]}")
                if 'actions' in insight and insight['actions']:
                    print(f"     Actions ({len(insight['actions'])}):")
                    for action in insight['actions'][:2]:
                        print(f"       - {action[:80]}")
            
            # Check GenAI status
            print("\n" + "=" * 70)
            if data.get('genai_enabled'):
                print("✅ GenAI IS WORKING! Recommendations generated by LLM.")
            else:
                print("⚠️  GenAI is using fallback mode (LLM unavailable)")
                print("    Check for error messages in policy insights")
            print("=" * 70)
            
            return data.get('genai_enabled', False)
        else:
            print(f"❌ Request failed with status {response.status_code}")
            print(response.text)
            return False
            
    except requests.exceptions.Timeout:
        print("❌ Request timed out (LLM generation might be taking too long)")
        return False
    except Exception as e:
        print(f"❌ Request failed: {e}")
        import traceback
        traceback.print_exc()
        return False

if __name__ == "__main__":
    print("\n🧪 API GenAI Integration Test\n")
    genai_working = test_api_endpoint()
    
    print("\n" + "=" * 70)
    print("Final Status:")
    print("=" * 70)
    if genai_working:
        print("✅ GenAI is fully operational!")
    else:
        print("⚠️  GenAI is not working as expected")
    print("=" * 70)
